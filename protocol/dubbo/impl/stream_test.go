func fixturePackages() map[string]DubboPackage {
	response := func(value any, exception error, attachments map[string]any) DubboPackage {
		return DubboPackage{Header: DubboHeader{Type: PackageResponse, ResponseStatus: Response_OK, SerialID: 2}, Body: &ResponsePayload{RspObj: value, Exception: exception, Attachments: attachments}}
	}
	request := func(args []any) DubboPackage {
		return DubboPackage{Header: DubboHeader{Type: PackageRequest_TwoWay, SerialID: 2}, Service: Service{Path: "codec.Echo", Interface: "codec.Echo", Method: "Echo", Version: "1", Group: "group"}, Body: NewRequestPayload(args, map[string]any{"tag": "baseline"})}
	}
	shared := map[string]string{"shared": "reference"}
	return map[string]DubboPackage{
		"request-scalars":      request([]any{"hello", int32(42), true, nil}),
		"request-reference":    request([]any{shared, shared}),
		"request-list":         request([]any{[]string{"a", "b"}}),
		"response-value":       response("hello", nil, nil),
		"response-null":        response(nil, nil, nil),
		"response-exception":   response(nil, errors.New("fixture failure"), nil),
		"response-attachments": response("hello", nil, map[string]any{DUBBO_VERSION_KEY: "2.0.2", "tag": "baseline"}),
		"heartbeat":            {Header: DubboHeader{Type: PackageHeartbeat, ResponseStatus: Response_OK, SerialID: 2}},
	}
}

// Fixtures were generated by the unmodified HessianSerializer at
// 6b04ac04bfc868060995dc9fa4e1dcc5138ad02b in an independent git archive.
func TestStreamBaselineFixtures(t *testing.T) {
	b, err := os.ReadFile("testdata/codec-baseline-6b04ac04.json")
	require.NoError(t, err)
	var fixtures []codecFixture
	require.NoError(t, json.Unmarshal(b, &fixtures))
	for _, fixture := range fixtures {
		t.Run(fixture.Name, func(t *testing.T) {
			pkg := fixturePackages()[fixture.Name]
			original, err := hex.DecodeString(fixture.Body)
			require.NoError(t, err)
			stream := StreamSerializer{Codec: &hessianstream.Codec{}}
			encoded, err := stream.Marshal(pkg)
			require.NoError(t, err)
			// Check both directions against the original bytes and legacy decoder.
			decode := func(serializer Serializer, data []byte) *DubboPackage {
				p := &DubboPackage{Header: pkg.Header}
				if !p.IsRequest() {
					p.Body = &ResponsePayload{RspObj: new(string)}
				}
				require.NoError(t, serializer.Unmarshal(data, p))
				return p
			}
			old := decode(HessianSerializer{}, original)
			migrated := decode(stream, original)
			reverse := decode(HessianSerializer{}, encoded)
			require.Equal(t, old.Service, migrated.Service)
			require.Equal(t, old.Service, reverse.Service)
			require.Equal(t, old.Body, migrated.Body)
			require.Equal(t, old.Body, reverse.Body)
			if fixture.Name == "response-value" || fixture.Name == "response-null" || fixture.Name == "heartbeat" {
				require.Equal(t, original, encoded)
			}
		})
	}
}

// This plugin uses encoding/json alone, so dynamic numbers and maps deliberately
// differ from Hessian's representation.
type independentJSONStream struct {
	closed *int
	life   *codecDecoderLife
}

func (independentJSONStream) Name() string                    { return "independent-json" }
func (independentJSONStream) Marshal(v any) ([]byte, error)   { return json.Marshal(v) }
func (independentJSONStream) Unmarshal(b []byte, v any) error { return json.Unmarshal(b, v) }
func (independentJSONStream) NewEncoder() (serialization.Encoder, error) {
	return &independentJSONEncoder{}, nil
}
func (c independentJSONStream) NewDecoder(b []byte) (serialization.Decoder, error) {
	id := 0
	if c.life != nil {
		c.life.created++
		id = c.life.created
	}
	return &independentJSONDecoder{Decoder: json.NewDecoder(bytes.NewReader(b)), closed: c.closed, life: c.life, id: id}, nil
}

type independentJSONEncoder struct{ bytes.Buffer }

func (e *independentJSONEncoder) Encode(v any) error      { return json.NewEncoder(&e.Buffer).Encode(v) }
func (e *independentJSONEncoder) Finish() ([]byte, error) { return bytes.Clone(e.Bytes()), nil }
func (*independentJSONEncoder) Close() error              { return nil }

type independentJSONDecoder struct {
	*json.Decoder
	closed *int
	life   *codecDecoderLife
	id     int
}

func (d *independentJSONDecoder) Close() error {
	if d.life != nil {
		d.life.closes[d.id]++
	}
	if d.closed != nil {
		(*d.closed)++
	}
	return nil
}

func TestIndependentJSONStreamRequest(t *testing.T) {
	s := StreamSerializer{Codec: independentJSONStream{}}
	original := fixturePackages()["request-scalars"]
	original.Service.Path = "codec.TypedArguments"
	original.Service.Interface = original.Service.Path
	_, err := common.ServiceMap.Register(original.Service.Interface, DUBBO, original.Service.Group, original.Service.Version, &StreamArgumentService{})
	require.NoError(t, err)
	t.Cleanup(func() {
		require.NoError(t, common.ServiceMap.UnRegister(original.Service.Interface, DUBBO, common.ServiceKey(original.Service.Interface, original.Service.Group, original.Service.Version)))
	})
	encoded, err := s.Marshal(original)
	require.NoError(t, err)
	decoded := DubboPackage{Header: original.Header}
	require.NoError(t, s.Unmarshal(encoded, &decoded))
	require.Equal(t, original.Service, decoded.Service)
	payload := decoded.Body.(map[string]any)
	require.Equal(t, []any{"hello", int32(42), true, nil}, payload["args"])
	require.Equal(t, "baseline", payload["attachments"].(map[string]any)["tag"])
}
func TestIndependentJSONStreamResponse(t *testing.T) {
	type object struct{ Value string }
	for _, test := range []struct {
		name   string
		value  any
		target any
	}{
		{"string", "expected", new(string)}, {"integer", int32(42), new(int32)},
		{"struct", object{"typed"}, new(object)}, {"map", map[string]int{"answer": 42}, new(map[string]int)},
	} {
		t.Run(test.name, func(t *testing.T) {
			s := StreamSerializer{Codec: independentJSONStream{}}
			p := DubboPackage{Header: DubboHeader{Type: PackageResponse, ResponseStatus: Response_OK}, Body: &ResponsePayload{RspObj: test.value, Attachments: map[string]any{"dubbo": "2.0.2", "tag": "reply"}}}
			encoded, err := s.Marshal(p)
			require.NoError(t, err)
			decoded := DubboPackage{Header: p.Header, Body: &ResponsePayload{RspObj: test.target}}
			require.NoError(t, s.Unmarshal(encoded, &decoded))
			require.Equal(t, test.value, reflect.ValueOf(test.target).Elem().Interface())
			require.Equal(t, "reply", decoded.Body.(*ResponsePayload).Attachments["tag"])
		})
	}
	for _, test := range []struct {
		name, wire string
		wantError  bool
	}{
		{"null", "2", false}, {"exception", "0\n\"failed\"", false},
		{"null-attachments", "5\n{\"tag\":\"reply\"}", false},
		{"exception-attachments", "3\n\"failed\"\n{\"tag\":\"reply\"}", false},
		{"unknown-flag", "99", true}, {"fractional-flag", "1.5", true},
		{"string-flag", "\"1\"", true}, {"truncated-value", "1", true},
		{"wrong-value-type", "1\n42", true}, {"wrong-attachments", "4\n\"value\"\n[]", true},
	} {
		t.Run(test.name, func(t *testing.T) {
			life := newCodecDecoderLife()
			s := StreamSerializer{Codec: independentJSONStream{life: life}}
			p := DubboPackage{Header: DubboHeader{Type: PackageResponse, ResponseStatus: Response_OK}, Body: &ResponsePayload{RspObj: new(string)}}
			err := s.Unmarshal([]byte(test.wire), &p)
			if test.wantError {
				require.Error(t, err)
			} else {
				require.NoError(t, err)
				if strings.HasPrefix(test.name, "exception") {
					require.EqualError(t, p.Body.(*ResponsePayload).Exception, "failed")
				}
			}
			life.check(t)
		})
	}
}

