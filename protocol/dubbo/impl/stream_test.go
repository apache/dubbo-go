func TestJSONStreamArgumentSignature(t *testing.T) {
	path := "codec.Signature"
	_, err := common.ServiceMap.Register(path, DUBBO, "", "", &StreamArgumentService{})
	require.NoError(t, err)
	t.Cleanup(func() { require.NoError(t, common.ServiceMap.UnRegister(path, DUBBO, common.ServiceKey(path, "", ""))) })
	for _, test := range []struct {
		name, method, argument string
		expected               any
		bad                    bool
	}{
		{"int32", "Number", "42", int32(42), false},
		{"int64-precision", "Wide", "9007199254740993", int64(9007199254740993), false},
		{"fractional", "Number", "1.5", nil, true},
		{"overflow", "Number", "2147483648", nil, true},
		{"wrong-type", "Number", "\"42\"", nil, true},
	} {
		t.Run(test.name, func(t *testing.T) {
			life := newCodecDecoderLife()
			s := StreamSerializer{Codec: independentJSONStream{life: life}}
			var wire bytes.Buffer
			encoder := json.NewEncoder(&wire)
			for _, field := range []string{"2.0.2", path, "", test.method, "I"} {
				require.NoError(t, encoder.Encode(field))
			}
			wire.WriteString(test.argument + "\n{}")
			p := DubboPackage{Header: DubboHeader{Type: PackageRequest_TwoWay}}
			err := s.Unmarshal(wire.Bytes(), &p)
			if test.bad {
				require.ErrorContains(t, err, "decode argument 0")
			} else {
				require.NoError(t, err)
				require.Equal(t, test.expected, p.Body.(map[string]any)["args"].([]any)[0])
			}
			life.check(t)
		})
	}
}

type codecDecoderLife struct {
	created int
	closes  map[int]int
}

func newCodecDecoderLife() *codecDecoderLife { return &codecDecoderLife{closes: map[int]int{}} }
func (l *codecDecoderLife) check(t *testing.T) {
	t.Helper()
	require.Len(t, l.closes, l.created)
	for id := 1; id <= l.created; id++ {
		require.Equal(t, 1, l.closes[id], "decoder %d", id)
	}
}

type codecFaultStream struct {
	independentJSONStream
	stage                                           string
	primary, cleanup                                error
	encodes, decoders, decoderCloses, encoderCloses int
}

func (c *codecFaultStream) NewEncoder() (serialization.Encoder, error) {
	if c.stage == "new-encoder" {
		return nil, c.primary
	}
	return &codecFaultEncoder{codecFaultStream: c}, nil
}
func (c *codecFaultStream) NewDecoder(b []byte) (serialization.Decoder, error) {
	c.decoders++
	if c.stage == "new-decoder" || c.stage == "replay-new" && c.decoders == 2 {
		return nil, c.primary
	}
	return &codecFaultDecoder{codecFaultStream: c, Decoder: json.NewDecoder(bytes.NewReader(b)), replay: c.decoders == 2}, nil
}

type codecFaultEncoder struct {
	*codecFaultStream
	bytes.Buffer
}

func (e *codecFaultEncoder) Encode(v any) error {
	e.encodes++
	if e.stage == "encode" {
		return e.primary
	}
	return json.NewEncoder(&e.Buffer).Encode(v)
}
func (e *codecFaultEncoder) Finish() ([]byte, error) {
	if e.stage == "finish" {
		return nil, e.primary
	}
	return bytes.Clone(e.Bytes()), nil
}
func (e *codecFaultEncoder) Close() error { e.encoderCloses++; return e.cleanup }

type codecFaultDecoder struct {
	*codecFaultStream
	*json.Decoder
	replay bool
	reads  int
}

func (d *codecFaultDecoder) Decode(v any) error {
	d.reads++
	if d.stage == "decode" || d.stage == "replay-decode" && d.replay && d.reads == 6 {
		return d.primary
	}
	if d.stage == "decode-panic" {
		panic("invalid stream")
	}
	return d.Decoder.Decode(v)
}
func (d *codecFaultDecoder) Close() error { d.decoderCloses++; return d.cleanup }
func TestCodecStreamFailureCleanup(t *testing.T) {
	primary, cleanup := errors.New("primary"), errors.New("close")
	for _, stage := range []string{"new-encoder", "encode", "finish", "close-encoder"} {
		t.Run(stage, func(t *testing.T) {
			c := &codecFaultStream{stage: stage, primary: primary, cleanup: cleanup}
			_, err := (StreamSerializer{Codec: c}).Marshal(fixturePackages()["request-scalars"])
			if stage == "close-encoder" {
				require.ErrorIs(t, err, cleanup)
			} else {
				require.ErrorIs(t, err, primary)
			}
			expected := 1
			if stage == "new-encoder" {
				expected = 0
			}
			require.Equal(t, expected, c.encoderCloses)
			c.stage = ""
			c.cleanup = nil
			_, err = (StreamSerializer{Codec: c}).Marshal(fixturePackages()["request-scalars"])
			require.NoError(t, err)
		})
	}
	path := "codec.ReplayFailure"
	_, err := common.ServiceMap.Register(path, DUBBO, "", "", &StreamArgumentService{})
	require.NoError(t, err)
	t.Cleanup(func() { _ = common.ServiceMap.UnRegister(path, DUBBO, common.ServiceKey(path, "", "")) })
	for _, stage := range []string{"new-decoder", "decode", "decode-panic", "close-decoder", "replay-new", "replay-decode"} {
		t.Run(stage, func(t *testing.T) {
			c := &codecFaultStream{stage: stage, primary: primary, cleanup: cleanup}
			wire := codecRequestWire(t, path, "Number", "I", []any{int32(42)}, nil)
			p := DubboPackage{Header: DubboHeader{Type: PackageRequest_TwoWay}}
			err := (StreamSerializer{Codec: c}).Unmarshal(wire, &p)
			switch stage {
			case "close-decoder":
				require.ErrorIs(t, err, cleanup)
			case "decode-panic":
				require.ErrorContains(t, err, "invalid Dubbo stream")
			default:
				require.ErrorIs(t, err, primary)
			}
			created := c.decoders
			if stage == "new-decoder" || stage == "replay-new" {
				created--
			}
			require.Equal(t, created, c.decoderCloses)
			c.stage = ""
			c.cleanup = nil
			require.NoError(t, (StreamSerializer{Codec: c}).Unmarshal(wire, &p))
		})
	}
}
func codecRequestWire(t *testing.T, path, method, types string, args []any, attachments map[string]any) []byte {
	t.Helper()
	var b bytes.Buffer
	e := json.NewEncoder(&b)
	for _, field := range []string{"2.0.2", path, "", method, types} {
		require.NoError(t, e.Encode(field))
	}
	for _, arg := range args {
		require.NoError(t, e.Encode(arg))
	}
	require.NoError(t, e.Encode(attachments))
	return b.Bytes()
}

