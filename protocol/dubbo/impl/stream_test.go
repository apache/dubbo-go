func TestCodecStreamSignatureRouting(t *testing.T) {
	path := "codec.SignatureRouting"
	for _, binding := range []struct {
		group, version string
		svc            common.RPCService
	}{{"numeric", "", &StreamArgumentService{}}, {"text", "", &CodecStringArgumentService{}}, {"", "v2", &CodecStringArgumentService{}}} {
		_, err := common.ServiceMap.Register(path, DUBBO, binding.group, binding.version, binding.svc)
		require.NoError(t, err)
		t.Cleanup(func() {
			_ = common.ServiceMap.UnRegister(path, DUBBO, common.ServiceKey(path, binding.group, binding.version))
		})
	}
	for _, test := range []struct {
		name, group, version, method, desc string
		args                               []any
		want                               []any
		bad                                bool
	}{
		{"numeric-group", "numeric", "", "Number", "I", []any{int32(42)}, []any{int32(42)}, false},
		{"text-group", "text", "", "Number", "Ljava/lang/String;", []any{"42"}, []any{"42"}, false},
		{"text-version", "", "v2", "Number", "Ljava/lang/String;", []any{"v2"}, []any{"v2"}, false},
		{"arity", "numeric", "", "Number", "II", []any{1, 2}, nil, true},
		{"unknown-service", "absent", "", "Number", "I", []any{42}, []any{float64(42)}, false},
		{"unknown-method", "numeric", "", "Absent", "I", []any{42}, []any{float64(42)}, false},
		{"catch-all", "text", "", "CatchAll", "II", []any{1, 2}, []any{float64(1), float64(2)}, false},
		{"typed-nil", "text", "", "Pointer", "Ljava/lang/String;", []any{nil}, []any{(*string)(nil)}, false},
	} {
		t.Run(test.name, func(t *testing.T) {
			life := newCodecDecoderLife()
			s := StreamSerializer{Codec: independentJSONStream{life: life}}
			attachments := map[string]any{"group": test.group}
			wire := codecRequestWire(t, path, test.method, test.desc, test.args, attachments)
			if test.version != "" {
				var lines [][]byte
				d := json.NewDecoder(bytes.NewReader(wire))
				for {
					var v json.RawMessage
					if d.Decode(&v) != nil {
						break
					}
					lines = append(lines, v)
				}
				lines[2], _ = json.Marshal(test.version)
				wire = bytes.Join(lines, []byte("\n"))
			}
			p := DubboPackage{Header: DubboHeader{Type: PackageRequest_TwoWay}}
			err := s.Unmarshal(wire, &p)
			if test.bad {
				require.ErrorContains(t, err, "expects 1 arguments")
			} else {
				require.NoError(t, err)
				require.Equal(t, test.want, p.Body.(map[string]any)["args"])
			}
			life.check(t)
		})
	}
}
